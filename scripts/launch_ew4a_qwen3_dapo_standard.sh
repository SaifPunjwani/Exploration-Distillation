TMX_TRAJ_HEALTH_MIN_CORRECT="${TMX_TRAJ_HEALTH_MIN_CORRECT:-1}" \
TMX_TRAJ_TARGET_ACCEPTED="${TMX_TRAJ_TARGET_ACCEPTED:-48}" \
TMX_USE_XLA_WORLD_SIZE="${TMX_USE_XLA_WORLD_SIZE:-}" \
RUN_ARTIFACT_GCS_PREFIX="$RUN_ARTIFACT_GCS_PREFIX" \
RUN_SYNC_INTERVAL_SECONDS="${RUN_SYNC_INTERVAL_SECONDS:-90}" \
TPU_NAME="$TPU_NAME" \
ZONE="$ZONE" \
WORKERS="${WORKERS:-0}" \
