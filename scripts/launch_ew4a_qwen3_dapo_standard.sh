RUN_ARTIFACT_GCS_PREFIX="${RUN_ARTIFACT_GCS_PREFIX:-gs://llmvae-checkpoints/two-model-exploration/ew4a_qwen3_dapo_standard}"

log() {
  printf '[ew4a-dapo-std] %s\n' "$*"
}

log "launching Qwen3 two-model fit-safe DAPO-think canary"

# --- XLA and TPU tuning ---
TMX_GRPO_GRAD_CKPT="${TMX_GRPO_GRAD_CKPT:-1}" \
