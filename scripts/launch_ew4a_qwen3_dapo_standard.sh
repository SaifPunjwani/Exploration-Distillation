#!/usr/bin/env bash
set -euo pipefail
#
# Launch Qwen3-1.7B two-model training with a fit-safe DAPO-think canary.
#
# Addresses the methodological feedback while keeping the single-chip TPU path
# inside a range that has a chance to survive more than one GRPO step:
#   1. Random problem selection (not solvable-only)
#   2. Standard \boxed{} answer format (via reasoning_final style)
#   3. Thinking mode enabled for math reasoning
#   4. Shorter canary budget (12 Explorer steps, not 48)
#   5. Moderate generation lengths instead of the previously oversized 1024/768 path
#

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

TPU_NAME="${TPU_NAME:?set TPU_NAME to the TPU VM (slice) name}"
