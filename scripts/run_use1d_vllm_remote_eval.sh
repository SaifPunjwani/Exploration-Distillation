#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

VLLM_VENV_DIR="${VLLM_VENV_DIR:-$HOME/vllm_tpu_env}"
MODEL_NAME="${MODEL_NAME:-Qwen/Qwen2.5-Math-1.5B-Instruct}"
SERVED_MODEL_NAME="${SERVED_MODEL_NAME:-$MODEL_NAME}"
TOKENIZER_NAME="${TOKENIZER_NAME:-$MODEL_NAME}"
RUN_NAME="${RUN_NAME:-use1d_vllm_eval_$(date +%Y%m%d_%H%M%S)}"
PORT="${PORT:-8000}"
TP_SIZE="${TP_SIZE:-4}"
BENCHMARK_DATASET_NAME="${BENCHMARK_DATASET_NAME:-aime_2024}"
BENCHMARK_DATASET_CONFIG_NAME="${BENCHMARK_DATASET_CONFIG_NAME:-}"
MAX_BENCHMARK="${MAX_BENCHMARK:-1}"
BENCHMARK_NUM_ROLLOUTS="${BENCHMARK_NUM_ROLLOUTS:-32}"
BENCHMARK_ROLLOUT_TEMPERATURE="${BENCHMARK_ROLLOUT_TEMPERATURE:-1.0}"
BENCHMARK_ROLLOUT_TOP_P="${BENCHMARK_ROLLOUT_TOP_P:-1.0}"
BENCHMARK_ROLLOUT_TOP_K="${BENCHMARK_ROLLOUT_TOP_K:-0}"
BENCHMARK_ROLLOUT_PASS_K="${BENCHMARK_ROLLOUT_PASS_K:-1,4,8,16,32}"
BENCHMARK_ROLLOUT_MAX_COMPLETION_LEN="${BENCHMARK_ROLLOUT_MAX_COMPLETION_LEN:-16384}"
REQUEST_CONCURRENCY="${REQUEST_CONCURRENCY:-32}"
REQUEST_TIMEOUT_SECONDS="${REQUEST_TIMEOUT_SECONDS:-1800}"
MAX_PROMPT_LEN="${MAX_PROMPT_LEN:-2048}"
MAX_MODEL_LEN="${MAX_MODEL_LEN:-32768}"
GPU_MEMORY_UTILIZATION="${GPU_MEMORY_UTILIZATION:-0.90}"
MAX_NUM_SEQS="${MAX_NUM_SEQS:-32}"
MAX_NUM_BATCHED_TOKENS="${MAX_NUM_BATCHED_TOKENS:-65536}"
THINKING_MODE="${THINKING_MODE:-auto}"
PROBLEM_SHARD_INDEX="${PROBLEM_SHARD_INDEX:-0}"
PROBLEM_SHARD_COUNT="${PROBLEM_SHARD_COUNT:-1}"
USE_WANDB="${USE_WANDB:-1}"
WANDB_GROUP="${WANDB_GROUP:-use1d_vllm_aime}"
RUN_ARTIFACT_GCS_PREFIX="${RUN_ARTIFACT_GCS_PREFIX:-}"
RUN_SYNC_INTERVAL_SECONDS="${RUN_SYNC_INTERVAL_SECONDS:-90}"
VLLM_ENV_CACHE_GCS_URI="${VLLM_ENV_CACHE_GCS_URI:-}"
SKIP_SERVER_LAUNCH="${SKIP_SERVER_LAUNCH:-0}"

SERVER_SESSION="vllm_server_${RUN_NAME}"
BENCH_SESSION="vllm_bench_${RUN_NAME}"
SYNC_SESSION="vllm_sync_${RUN_NAME}"
SERVER_BASE_URL="http://127.0.0.1:${PORT}/v1"
RUN_DIR="runs/${RUN_NAME}"
SERVER_LOG="${RUN_DIR}/server.log"
BENCH_LOG="${RUN_DIR}/benchmark.log"
SUMMARY_PATH="${RUN_DIR}/analysis/benchmark_summary.json"
GCS_RUN_DIR=""
if [ -n "$RUN_ARTIFACT_GCS_PREFIX" ]; then
  GCS_RUN_DIR="${RUN_ARTIFACT_GCS_PREFIX%/}/${RUN_NAME}"
fi

mkdir -p "$RUN_DIR"

if [ -n "$GCS_RUN_DIR" ] && gcloud storage ls "$GCS_RUN_DIR" >/dev/null 2>&1; then
  gcloud storage rsync -r "$GCS_RUN_DIR" "$RUN_DIR" >/dev/null 2>&1 || true
fi

if [ ! -x "$VLLM_VENV_DIR/bin/python" ]; then
  VLLM_VENV_DIR="$VLLM_VENV_DIR" VLLM_ENV_CACHE_GCS_URI="$VLLM_ENV_CACHE_GCS_URI" bash scripts/bootstrap_vllm_tpu_env.sh
fi

source "$VLLM_VENV_DIR/bin/activate"
python - <<'PY' >/dev/null 2>&1 || python -m pip install -q datasets wandb
import datasets  # noqa: F401
import wandb  # noqa: F401
PY

tmux kill-session -t "$BENCH_SESSION" >/dev/null 2>&1 || true
tmux kill-session -t "$SYNC_SESSION" >/dev/null 2>&1 || true

if [ "$SKIP_SERVER_LAUNCH" != "1" ]; then
  tmux kill-session -t "$SERVER_SESSION" >/dev/null 2>&1 || true
  tmux new-session -d -s "$SERVER_SESSION" \
    "cd '$ROOT_DIR' && MODEL_NAME='$MODEL_NAME' SERVED_MODEL_NAME='$SERVED_MODEL_NAME' PORT='$PORT' TP_SIZE='$TP_SIZE' MAX_MODEL_LEN='$MAX_MODEL_LEN' GPU_MEMORY_UTILIZATION='$GPU_MEMORY_UTILIZATION' MAX_NUM_SEQS='$MAX_NUM_SEQS' MAX_NUM_BATCHED_TOKENS='$MAX_NUM_BATCHED_TOKENS' VLLM_VENV_DIR='$VLLM_VENV_DIR' bash scripts/run_vllm_server.sh > '$SERVER_LOG' 2>&1"
fi

echo "[use1d-vllm] waiting for server at $SERVER_BASE_URL (skip_launch=$SKIP_SERVER_LAUNCH)"
for _ in $(seq 1 180); do
  if curl -sf "$SERVER_BASE_URL/models" >/dev/null 2>&1; then
    echo "[use1d-vllm] server ready"
    break
  fi
  sleep 10
done

if ! curl -sf "$SERVER_BASE_URL/models" >/dev/null 2>&1; then
  echo "[use1d-vllm] server failed to become ready" >&2
  exit 1
fi

tmux new-session -d -s "$BENCH_SESSION" \
  "cd '$ROOT_DIR' && PYTHON_BIN='$VLLM_VENV_DIR/bin/python' SERVER_BASE_URL='$SERVER_BASE_URL' MODEL_NAME='$MODEL_NAME' SERVED_MODEL_NAME='$SERVED_MODEL_NAME' TOKENIZER_NAME='$TOKENIZER_NAME' RUN_NAME='$RUN_NAME' ROLE_NAME='base' BENCHMARK_DATASET_NAME='$BENCHMARK_DATASET_NAME' BENCHMARK_DATASET_CONFIG_NAME='$BENCHMARK_DATASET_CONFIG_NAME' MAX_BENCHMARK='$MAX_BENCHMARK' BENCHMARK_NUM_ROLLOUTS='$BENCHMARK_NUM_ROLLOUTS' BENCHMARK_ROLLOUT_TEMPERATURE='$BENCHMARK_ROLLOUT_TEMPERATURE' BENCHMARK_ROLLOUT_TOP_P='$BENCHMARK_ROLLOUT_TOP_P' BENCHMARK_ROLLOUT_TOP_K='$BENCHMARK_ROLLOUT_TOP_K' BENCHMARK_ROLLOUT_PASS_K='$BENCHMARK_ROLLOUT_PASS_K' BENCHMARK_ROLLOUT_MAX_COMPLETION_LEN='$BENCHMARK_ROLLOUT_MAX_COMPLETION_LEN' REQUEST_CONCURRENCY='$REQUEST_CONCURRENCY' REQUEST_TIMEOUT_SECONDS='$REQUEST_TIMEOUT_SECONDS' MAX_PROMPT_LEN='$MAX_PROMPT_LEN' THINKING_MODE='$THINKING_MODE' PROBLEM_SHARD_INDEX='$PROBLEM_SHARD_INDEX' PROBLEM_SHARD_COUNT='$PROBLEM_SHARD_COUNT' USE_WANDB='$USE_WANDB' WANDB_GROUP='$WANDB_GROUP' bash scripts/run_vllm_aime_rollout_eval.sh > '$BENCH_LOG' 2>&1"

if [ -n "$GCS_RUN_DIR" ]; then
  tmux new-session -d -s "$SYNC_SESSION" \
    "cd '$ROOT_DIR' && while true; do gcloud storage rsync -r '$RUN_DIR' '$GCS_RUN_DIR' >/dev/null 2>&1 || true; if [ -f '$SUMMARY_PATH' ]; then gcloud storage rsync -r '$RUN_DIR' '$GCS_RUN_DIR' >/dev/null 2>&1 || true; break; fi; sleep '$RUN_SYNC_INTERVAL_SECONDS'; done"
fi

echo "[use1d-vllm] benchmark session started: $BENCH_SESSION"
if [ "$SKIP_SERVER_LAUNCH" != "1" ]; then
  echo "[use1d-vllm] server session: $SERVER_SESSION"
else
  echo "[use1d-vllm] reusing existing server on $SERVER_BASE_URL"
fi
if [ -n "$GCS_RUN_DIR" ]; then
  echo "[use1d-vllm] sync session: $SYNC_SESSION"
fi
